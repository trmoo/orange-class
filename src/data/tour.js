/** → [{ pnid, 값: [19개 — 번호 또는 null], Q11 }] */
export function 설문만들기(씨앗 = 2025) {
  const rnd = 난수(씨앗);
  const 결과 = [];
  for (let n = 0; n < 응답수; n++) {
    let r = rnd(), 내성향 = 성향[0];
    for (const p of 성향) { if (r < p.비율) { 내성향 = p; break; } r -= p.비율; }
    const 값 = 바탕.map((b, i) => {
      const p = Math.max(b, 내성향.더[i] ?? 0);
      return rnd() < p ? i + 1 : null;
    });
    if (값.every((v) => v === null)) 값[1] = 2; // 아무것도 안 고른 응답은 쇼핑으로
    // 전반적 만족도 1~5점 — 대부분 만족한다
    const q = rnd();
    const Q11 = q < 0.004 ? 1 : q < 0.009 ? 2 : q < 0.026 ? 3 : q < 0.36 ? 4 : 5;
    결과.push({ pnid: 100001 + n, 값, Q11 });
  }
  return 결과;
}

/** 응답 → 비트 묶음 (고른 활동 i 가 i 번째 비트) */
export const 묶음으로 = (응답) => 응답.값.reduce((m, v, i) => (v === null ? m : m | (1 << i)), 0);
