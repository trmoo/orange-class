import { 난수, 정규 } from '../lib/stats.js';

// 달마다의 평균 기온(℃)·비 올 확률·비 양 평균(mm)·평균 풍속(m/s)
const 달 = [
  { 기온: -1.5, 비: 0.13, 양: 4, 바람: 2.5 }, { 기온: 1.5, 비: 0.17, 양: 6, 바람: 2.6 }, { 기온: 7, 비: 0.22, 양: 7, 바람: 2.8 },
  { 기온: 13.5, 비: 0.25, 양: 9, 바람: 2.7 }, { 기온: 19, 비: 0.27, 양: 10, 바람: 2.3 }, { 기온: 23.5, 비: 0.33, 양: 14, 바람: 2.0 },
  { 기온: 26.5, 비: 0.58, 양: 26, 바람: 2.0 }, { 기온: 28.5, 비: 0.4, 양: 20, 바람: 1.9 }, { 기온: 24, 비: 0.3, 양: 15, 바람: 1.8 },
  { 기온: 16, 비: 0.18, 양: 8, 바람: 1.9 }, { 기온: 8.5, 비: 0.22, 양: 6, 바람: 2.2 }, { 기온: 1, 비: 0.16, 양: 4, 바람: 2.5 },
];
const 일수 = [31, 29, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];
// 해가 떠 있는 시간(대략)
const 낮길이 = [9.8, 10.8, 12, 13.2, 14.2, 14.7, 14.5, 13.6, 12.4, 11.2, 10.1, 9.5];

export const 속성 = ['강수량(mm)', '평균기온(°C)', '평균풍속(m/s)', '일조합(hr)'];

export function 날씨만들기(씨앗 = 2024) {
  const rnd = 난수(씨앗);
  const 행들 = [];
  let 어제편차 = 0;
  for (let m = 0; m < 12; m++) {
    for (let d = 1; d <= 일수[m]; d++) {
      const M = 달[m];
      // 기온은 하루 전과 이어지게(따뜻한 날이 며칠 이어진다)
      어제편차 = 0.6 * 어제편차 + 1.9 * 정규(rnd);
      const 비옴 = rnd() < M.비;
      let 강수 = null;
      if (비옴) {
        강수 = -M.양 * Math.log(1 - rnd() * 0.999);
        if (m === 6 && rnd() < 0.08) 강수 += 60 + 70 * rnd(); // 장마철 큰비
        강수 = Math.max(0.1, Math.round(강수 * 10) / 10);
      }
      // 겨울·봄의 찬 바람 부는 날은 바람이 세고 기온이 낮다
      const 센바람 = (m <= 3 || m >= 10) && rnd() < 0.07;
      let 바람 = M.바람 + 0.55 * 정규(rnd) + (센바람 ? 2.6 + rnd() * 1.5 : 0) + (비옴 ? 0.4 : 0);
      바람 = Math.max(0.5, Math.round(바람 * 10) / 10);
      const 기온 = Math.round((M.기온 + 어제편차 - (센바람 ? 3 : 0) - (비옴 && m >= 5 && m <= 8 ? 1.5 : 0)) * 10) / 10;
      const 맑음 = 비옴 ? 0.05 + 0.25 * rnd() : Math.min(1, 0.45 + 0.55 * rnd());
      const 일조 = Math.round(Math.max(0, 낮길이[m] * 0.85 * 맑음) * 10) / 10;
      const 일시 = `2024-${String(m + 1).padStart(2, '0')}-${String(d).padStart(2, '0')}`;
      행들.push({ 일시, 값: [강수, 기온, 바람, 일조] });
    }
  }
  return 행들;
}
